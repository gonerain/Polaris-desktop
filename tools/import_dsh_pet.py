"""Build the selected non-commercial dsh-pet pack; FFmpeg is build-time only.

Usage: .venv/Scripts/python tools/import_dsh_pet.py UPSTREAM --ffmpeg PATH
The checkout must match SOURCE_COMMIT. No network requests or runtime changes.
"""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

from PySide6.QtGui import QImageReader

SOURCE_COMMIT = "86181ce1660a57ab27336630bab5b344de71b28c"
# action: source filename, start seconds, duration seconds, frame rate
SELECTION = {
    "idle": ("待机呼吸休闲", 0, 10, 8),
    "wave": ("点击回应-元气挥手", 1.3, 2.5, 12),
    "drowsy": ("哈欠连天", 0.7, 3.2, 10),
    "sleep": ("原地小憩沉眠", 2.5, 6, 6),
    "wake": ("打瞌睡被惊醒", 4, 2.2, 12),
    "drag": ("被鼠标拖拽悬空反馈", 1, 4, 8),
    "complete": ("工作状态-雀跃庆祝", 1.5, 3, 12),
    "stretch": ("超大伸懒腰", 1, 7, 10),
    "puzzle": ("原地专心玩魔方", 0, 8, 10),
    "glance": ("东张西望", 0, 5, 10),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    parser.add_argument("--ffmpeg", default=shutil.which("ffmpeg"))
    args = parser.parse_args()
    if not args.ffmpeg:
        parser.error("FFmpeg with libvpx-vp9 and libwebp_anim is required")
    revision = subprocess.check_output(
        ["git", "-C", str(args.upstream), "rev-parse", "HEAD"], text=True
    ).strip()
    if revision != SOURCE_COMMIT:
        parser.error(f"expected checkout {SOURCE_COMMIT}, got {revision}")
    source_dir = args.upstream / "dsh-pet/assets/webm"
    output = Path(__file__).resolve().parents[1] / "assets/dsh-pet"
    output.mkdir(parents=True, exist_ok=True)
    sources = {}
    bounds = []
    commands = {}
    for action, (name, start, duration, fps) in SELECTION.items():
        path = source_dir / (name + ".webm")
        sources[action] = {"file": str(path.relative_to(args.upstream)).replace("\\", "/"),
                           "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                           "start": start, "seconds": duration, "fps": fps}
        command = [args.ffmpeg, "-hide_banner", "-c:v", "libvpx-vp9", "-i", str(path),
                   "-ss", str(start), "-t", str(duration)]
        commands[action] = command
        scan = subprocess.run(command + ["-vf", f"fps={fps},alphaextract,bbox=min_val=32",
                              "-f", "null", "-"], capture_output=True, check=True)
        bounds.extend(tuple(map(int, match)) for match in re.findall(
            r"x1:(\d+) x2:(\d+) y1:(\d+) y2:(\d+)", scan.stderr.decode("utf-8", errors="replace")))
    if not bounds:
        raise RuntimeError("No alpha foreground found; refusing to build blank assets")
    # One common crop, including effects and movement, avoids per-action size jumps.
    left = max(0, (min(b[0] for b in bounds) - 8) // 2 * 2)
    top = max(0, (min(b[2] for b in bounds) - 8) // 2 * 2)
    right = min(640, (max(b[1] for b in bounds) + 10) // 2 * 2)
    bottom = min(360, (max(b[3] for b in bounds) + 10) // 2 * 2)
    crop = f"{right-left}:{bottom-top}:{left}:{top}"
    clips = {}
    for action, (_, _, _, fps) in SELECTION.items():
        path = output / (action + ".webp")
        filters = (f"fps={fps},crop={crop},scale=240:240:force_original_aspect_ratio=decrease,"
                   "format=rgba,pad=256:256:(ow-iw)/2:(oh-ih)/2:color=black@0")
        subprocess.run(commands[action] + ["-v", "error", "-vf", filters, "-an",
                       "-c:v", "libwebp_anim", "-quality", "82", "-compression_level", "4",
                       "-loop", "0", "-y", str(path)], check=True)
        reader = QImageReader(str(path))
        frames, duration = reader.imageCount(), 0
        if not reader.supportsAnimation() or frames < 2:
            raise RuntimeError(f"Qt cannot animate {path}")
        for index in range(frames):
            image = reader.read()
            if image.isNull() or not image.hasAlphaChannel() or image.pixelColor(0, 0).alpha():
                raise RuntimeError(f"Invalid transparent frame: {path} #{index}")
            duration += reader.nextImageDelay()
            if action == "idle" and index == 0:
                if not image.save(str(output / "poster.webp"), "WEBP", 90):
                    raise RuntimeError("Cannot save static poster")
        clips[action] = {"file": action + ".webp", "duration": duration}
        sources[action].update(frames=frames, duration=duration,
                               output_sha256=hashlib.sha256(path.read_bytes()).hexdigest())
    clips["drop"] = {"file": "poster.webp", "duration": 350}
    (output / "Clips.js").write_text(
        ".pragma library\n\n// Generated by tools/import_dsh_pet.py.\nvar clips = "
        + json.dumps(clips, indent=4) + "\n", encoding="utf-8")
    (output / "SOURCES.json").write_text(json.dumps(
        {"repository": "https://github.com/PC2005-cloud/dsh-pet", "commit": SOURCE_COMMIT,
         "common_crop": crop, "size": 256, "clips": sources}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8")
    print(f"Built {len(SELECTION)} clips, common crop {crop}; animated WebP, no runtime FFmpeg")


if __name__ == "__main__":
    main()
